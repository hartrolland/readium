function toggleContent0() {
  var elements0 = document.querySelectorAll('.hide0');
  elements0.forEach(function(el0) {
    el0.style.display = (el0.style.display === 'inline') ? 'none' : 'inline';
  });

  var dots0 = document.querySelectorAll('.dots0');
  dots0.forEach(function(dts0) {
    dts0.style.display = (dts0.style.display === 'none') ? 'inline' : 'none';
  });

  var text0 = document.querySelectorAll('.text0');
  text0.forEach(function(txt0) {
    txt0.style.fontWeight = (txt0.style.fontWeight === 'bold') ? 'normal' : 'bold';
  });

  var button0 = document.querySelectorAll('.button0');
  button0.forEach(function(btn0) {
    btn0.innerHTML = (btn0.innerHTML === 'less') ? 'more' : 'less';
  });
}

